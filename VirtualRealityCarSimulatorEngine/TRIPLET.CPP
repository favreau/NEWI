
#include "TRIPLET.H"
#include <math.h>

//===================================================================================================================//
// Constructor
//===================================================================================================================//
MyTriplet::MyTriplet()
{
  x  = 0;  y = 0;  z = 0;
  Px = 0; Py = 0; Pz = 0;
  P.x = 0;
  P.y = 0;
}

//===================================================================================================================//
// Destructor
//===================================================================================================================//
MyTriplet::~MyTriplet()
{
}

//===================================================================================================================//
// Projects the triplet onto the projective plane
// Returns coordinates in P
//===================================================================================================================//
void MyTriplet::Projection(float Ax, float Ay, float Az)
{
  float lX = Px+Ax;
  float lY = Py+Ay;
  float lZ = Pz+Az;
  if (lZ == 0) lZ = 0.01;
  P.x = int(lX * KDistance / lZ);
  P.y = int(lY * KDistance / lZ);
}

//===================================================================================================================//
// Draws the triplet onto the screen
//===================================================================================================================//
void MyTriplet::Draw(HDC aDC,float CenterX, float CenterY, float Ax, float Ay, float Az)
{
  Projection(Ax,Ay,Az);
  Ellipse(aDC,CenterX+P.x+5,CenterY-P.y+5,CenterX+P.x-5,CenterY-P.y-5);
}

//===================================================================================================================//
// Initialises triplet coordinates
//===================================================================================================================//
void  MyTriplet::SetCoordinates(float Ax, float Ay, float Az)
{
  x  = Ax;  y  = Ay;  z  = Az;
  Px = float(Ax);  Py = float(Ay);  Pz = float(Az);
}

//===================================================================================================================//
// Restores initial coordinates
//===================================================================================================================//
void MyTriplet::Reset()
{
  Px = x;
  Py = y;
  Pz = z;
}

//===================================================================================================================//
// Get x value
//===================================================================================================================//
float MyTriplet::GetX(void)
{
  return x;
}

//===================================================================================================================//
// Get y value
//===================================================================================================================//
float MyTriplet::GetY(void)
{
  return y;
}

//===================================================================================================================//
// Get z value
//===================================================================================================================//
float MyTriplet::GetZ(void)
{
  return z;
}

//===================================================================================================================//
// Get 2D coordinates stored in P
//===================================================================================================================//
POINT MyTriplet::GetP(void)
{
  POINT lP;
  lP.x = x * KDistance / z;
  lP.y = y * KDistance / z;
  return lP; 
}

//===================================================================================================================//
// Translates the triplet
//===================================================================================================================//
void MyTriplet::Translation(float aX,float aY,float aZ)
{
  Px += float(aX);
  Py += float(aY);
  Pz += float(aZ);
}

//===================================================================================================================//
// rotates the triplet
//===================================================================================================================//
void MyTriplet::Rotation(float AXCenter,float AYCenter, float AZCenter, int AAxe, float AAngle)
{
  float A,B;
  float    Lx = Px - AXCenter,
	   Ly = Py - AYCenter,
	   Lz = Pz - AZCenter;

  float C = cos(AAngle*M_PI/180);
  float S = sin(AAngle*M_PI/180);
           
  switch (AAxe)
  {
  case 3: //z
    {
       A = Lx*C - Ly*S;
       B = Lx*S + Ly*C;
       Lx = A;
       Ly = B;
    };
    break;
  case 1: //x
    {
       A = Ly*C - Lz*S;
       B = Ly*S + Lz*C;
       Ly = A;
       Lz = B;
    };
    break;
  case 2: //y
    {
       A = Lz*S + Lx*C;
       B = Lz*C - Lx*S;
       Lx = A;
       Lz = B;
    };
    break;
  };
  Px = Lx + AXCenter;
  Py = Ly + AYCenter;
  Pz = Lz + AZCenter;
}